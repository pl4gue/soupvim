local create_gradient = function(start, finish, steps)
	local r1, g1, b1 =
		tonumber("0x" .. start:sub(2, 3)), tonumber("0x" .. start:sub(4, 5)), tonumber("0x" .. start:sub(6, 7))
	local r2, g2, b2 =
		tonumber("0x" .. finish:sub(2, 3)), tonumber("0x" .. finish:sub(4, 5)), tonumber("0x" .. finish:sub(6, 7))

	local r_step = (r2 - r1) / steps
	local g_step = (g2 - g1) / steps
	local b_step = (b2 - b1) / steps

	local gradient = {}
	for i = 1, steps do
		local r = math.floor(r1 + r_step * i)
		local g = math.floor(g1 + g_step * i)
		local b = math.floor(b1 + b_step * i)
		table.insert(gradient, string.format("#%02x%02x%02x", r, g, b))
	end

	return gradient
end

function M.apply_gradient_hl(text, gradient_start, gradient_end)
	gradient_start = gradient_start or "#78B892"
	gradient_end = gradient_end or "#c8ced7"

	local gradient = create_gradient(gradient_start, gradient_end, #text)

	local lines = {}
	for i, line in ipairs(text) do
		local tbl = {
			type = "text",
			val = line,
			opts = {
				hl = "HeaderGradient" .. i,
				position = "center",
			},
		}
		table.insert(lines, tbl)

		-- create hl group
		vim.api.nvim_set_hl(0, "HeaderGradient" .. i, { fg = gradient[i] })
	end

	return {
		type = "group",
		val = lines,
		opts = { position = "center" },
	}
end

local function utf8_char_len(str, pos)
	local byte = str:byte(pos)

	if not byte then
		return 0
	end
	if byte < 0x80 then
		return 1
	end
	if byte < 0xE0 then
		return 2
	end
	if byte < 0xF0 then
		return 3
	end
	if byte < 0xF8 then
		return 4
	end

	return 1
end

function M.colorize(header, color_map, colors)
	local color_names = {}

	for character, definition in pairs(colors) do
		local name = HIGHLIGHT_PREFIX .. character

		vim.api.nvim_set_hl(0, name, definition)
		color_names[character] = name
	end

	local colorized = {}

	for i, map_line in ipairs(color_map) do
		local result = {}
		local header_pos = 1

		for j = 1, #map_line do
			local character = map_line:byte(j)
			local length = utf8_char_len(header[i], header_pos)

			local color_name = color_names[string.char(character)]

			if color_name then
				result[#result + 1] = {
					color_name,
					header_pos - 1,
					header_pos - 1 + length,
				}
			end

			header_pos = header_pos + length
		end

		colorized[i] = result
	end

	return colorized
end

function M:setup_random(apply_gradient)
	local keys = vim.tbl_keys(self.headers)
	return self:setup(keys[math.random(1, #keys + 1)], apply_gradient)
end

function M:setup(header_name, apply_gradient)
	local header = self.headers[header_name]
	if header.is_color_map then
		local color_map = self.color_maps[header_name]

		header = {}
		for _, line in ipairs(color_map) do
			local header_line = [[]]
			for i = 1, #line do
				if line:sub(i, i) ~= " " then
					header_line = header_line .. "█"
				else
					header_line = header_line .. " "
				end
			end
			table.insert(header, header_line)
		end

		local val = self.colorize({ unpack(header) }, { unpack(color_map) }, color_map.colors)
		-- vim.print(vim.inspect(val))
		return { type = "text", val = header, opts = { hl = val, position = "center" } }
	elseif apply_gradient then
		return self.apply_gradient_hl({ unpack(header) }, header.gradient_start, header.gradient_finish)
	end

	return { type = "text", val = { unpack(header) }, opts = { position = "center" } }
end

return M
